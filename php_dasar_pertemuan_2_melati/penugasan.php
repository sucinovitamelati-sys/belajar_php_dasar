<?php

$a = 6;

// Operator Penugasan
$a += 4; // $a sekarang bernilai 10
echo $a . "<br>";

$a -= 2; // $a sekarang bernilai 8
echo $a . "<br>";

$a *= 5; // $a sekarang bernilai 40
echo $a . "<br>";

$a /= 8; // $a sekarang bernilai 5
echo $a . "<br>";

$a %= 2; // $a sekarang bernilai 1
echo $a . "<br>";

?>